/**
 * THEME REGISTRY - 12 genuinely different design systems.
 *
 * A theme is not a color. Each theme declares its own structural language:
 * layout family, navigation, hero architecture, type system, spacing scale,
 * radius/shadow language, card + section treatments, footer, decorative motifs,
 * and default section order. The palette is layered on top per-business from
 * the Excel "Primary Color". Two businesses on the same theme still diverge via
 * palette + the variation engine, but every theme reads as an independent
 * studio design.
 *
 * Fields consumed downstream:
 *  - tokens:   raw design tokens resolved into CSS custom properties (design/tokens.js)
 *  - hero/nav/serviceCard/reviewCard/footer/gallery: variant *keys* the
 *    component library branches on (components/index.js)
 *  - sectionOrder: default homepage section sequence (generator/pages.js)
 *  - mood: 'light' | 'dark' - drives base surface/text derivation
 *
 * The variation engine may override individual variant keys per business, but
 * the theme sets the coherent baseline so overrides never fight the design.
 */

